#!/usr/bin/env python3
"""
Icepi Zero – 20 hand taxels shown as a heatmap on the hand outline.
Uses the same serial format, port auto-detection and baseline as icepizeroo.py.

Taxel shapes and the taxel -> channel (S0..S23) mapping come from hand_layout.json
(generated by tools/extract_hand_layout.py from the hand DXF).

Keys (on the plot window):
  b      re-capture baseline (keep hands off)
  + / -  raise / lower the colour scale maximum
  l      toggle channel labels
"""

import json
import os
import sys

import matplotlib.pyplot as plt
import matplotlib.animation as animation
from matplotlib.collections import PatchCollection
from matplotlib.patches import Polygon
import matplotlib.patheffects as pe
import serial

from icepizeroo import (BAUD, BASELINE_SAMPLES, NUM_SENSORS,
                        find_active_port, find_packet, parse_packet)

LAYOUT_FILE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "hand_layout.json")
VMAX_START = 300        # counts above baseline shown as full colour
VMAX_STEPS = [25, 50, 100, 200, 300, 500, 1000, 2000, 5000]
TOUCH_THRESHOLD = 15    # same as icepizeroo.py
SMOOTHING = 0.3         # EMA weight of each new frame (1.0 = no smoothing)
CMAP = "inferno_r"


if __name__ == "__main__":
    with open(LAYOUT_FILE) as f:
        layout = json.load(f)
    taxels = layout["taxels"]

    PORT = find_active_port()
    if PORT is None:
        print("ERROR: No COM port is sending the expected data (header 0xAB, footer 0xFF).")
        sys.exit(1)
    print(f"Using {PORT} @ {BAUD}")
    try:
        ser = serial.Serial(PORT, BAUD, timeout=0.05)
        ser.reset_input_buffer()
    except serial.SerialException as e:
        print(f"ERROR: {e}")
        sys.exit(1)

    buf = bytearray()
    baseline = [0] * NUM_SENSORS
    baseline_ready = False
    baseline_acc = [0] * NUM_SENSORS
    baseline_cnt = 0
    shown = [0.0] * NUM_SENSORS     # smoothed, baseline-corrected values
    vmax = VMAX_START

    def capture_baseline():
        global baseline_ready, baseline_acc, baseline_cnt
        baseline_ready = False
        baseline_acc = [0] * NUM_SENSORS
        baseline_cnt = 0
        print("Capturing new baseline - keep hands off the sensors...")

    # ── plot setup ──
    fig, ax = plt.subplots(figsize=(11, 8))
    fig.canvas.manager.set_window_title("Hand Heatmap")
    ax.set_title("Icepi Zero – hand taxels (count − baseline)")
    ax.set_aspect("equal")
    ax.axis("off")

    for pts in layout["outline"]:
        xs, ys = zip(*pts)
        ax.plot(xs, ys, color="0.3", linewidth=1.0)

    # one patch per polygon; taxels made of two shapes get two patches
    patches, patch_channel = [], []
    for t in taxels:
        for pts in t["polygons"]:
            patches.append(Polygon(pts, closed=True))
            patch_channel.append(t["channel"])
    coll = PatchCollection(patches, cmap=CMAP, edgecolor="0.2", linewidth=0.6)
    coll.set_clim(0, vmax)
    coll.set_array([0.0] * len(patches))
    ax.add_collection(coll)
    cbar = fig.colorbar(coll, ax=ax, fraction=0.03, pad=0.02)
    cbar.set_label("count − baseline")

    labels = []
    for t in taxels:
        pts = max(t["polygons"], key=len)
        cx = sum(p[0] for p in pts) / len(pts)
        cy = sum(p[1] for p in pts) / len(pts)
        labels.append(ax.text(cx, cy, f"S{t['channel']}", ha="center", va="center",
                              fontsize=8, color="tab:blue", weight="bold",
                              path_effects=[pe.withStroke(linewidth=2.5, foreground="white")]))

    mapped = {t["channel"] for t in taxels}
    unmapped = [c for c in range(NUM_SENSORS) if c not in mapped]
    status_text = ax.text(0.01, 0.99, "", transform=ax.transAxes, va="top",
                          fontsize=9, family="monospace",
                          bbox=dict(boxstyle="round", facecolor="wheat", alpha=0.8))

    capture_baseline()

    def update(_frame):
        global buf, baseline_ready, baseline_acc, baseline_cnt, baseline

        data = ser.read(ser.in_waiting or 1)
        if data:
            buf.extend(data)

        acc = [0] * NUM_SENSORS
        n = 0
        while True:
            pkt, buf = find_packet(buf)
            if pkt is None:
                break
            raw_vals = [v for _, v in parse_packet(pkt)]
            if not baseline_ready:
                for i, v in enumerate(raw_vals):
                    baseline_acc[i] += v
                baseline_cnt += 1
                if baseline_cnt >= BASELINE_SAMPLES:
                    for i in range(NUM_SENSORS):
                        baseline[i] = baseline_acc[i] // baseline_cnt
                    baseline_ready = True
                    print("Baseline captured:", baseline)
                continue
            for i, v in enumerate(raw_vals):
                acc[i] += max(0, v - baseline[i])
            n += 1

        if not baseline_ready:
            status_text.set_text(f"Capturing baseline… {baseline_cnt}/{BASELINE_SAMPLES}")
            return [coll, status_text]
        if n:
            for i in range(NUM_SENSORS):
                shown[i] += SMOOTHING * (acc[i] / n - shown[i])

        coll.set_array([shown[c] for c in patch_channel])
        top = max(range(NUM_SENSORS), key=lambda i: shown[i])
        lines = [f"max: S{top} = {shown[top]:6.0f}   scale 0–{vmax}  (+/- to change, b = baseline)"]
        if unmapped:
            lines.append("not on hand: " + " ".join(
                f"S{c}={shown[c]:.0f}" + ("*" if shown[c] > TOUCH_THRESHOLD else "") for c in unmapped))
        status_text.set_text("\n".join(lines))
        return [coll, status_text]

    def on_key(event):
        global vmax
        if event.key == "b":
            capture_baseline()
        elif event.key in ("+", "=", "-"):
            i = min(range(len(VMAX_STEPS)), key=lambda k: abs(VMAX_STEPS[k] - vmax))
            i = min(i + 1, len(VMAX_STEPS) - 1) if event.key != "-" else max(i - 1, 0)
            vmax = VMAX_STEPS[i]
            coll.set_clim(0, vmax)
        elif event.key == "l":
            for t in labels:
                t.set_visible(not t.get_visible())

    fig.canvas.mpl_connect("key_press_event", on_key)
    ani = animation.FuncAnimation(fig, update, interval=30,
                                  blit=False, cache_frame_data=False)

    print("Hand heatmap running - keep hands off for the first second (baseline capture)")
    try:
        plt.show()
    except KeyboardInterrupt:
        pass
    finally:
        ser.close()
        print("Closed.")
