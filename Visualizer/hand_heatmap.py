#!/usr/bin/env python3
"""
Icepi Zero – 20 hand taxels shown as a heatmap on the hand outline.
Uses the same serial format, port auto-detection and baseline as icepizeroo.py.

Taxel shapes and the taxel -> channel (S0..S23) mapping come from hand_layout.json
(generated by tools/extract_hand_layout.py from the hand DXF).

Press "a" to divide each taxel's value by its area (counts per cm²), so large
pads do not look stronger just because they are large.

If hand_layout.json has a "gain" per taxel (from hand_gain_calibrate.py), values are
multiplied by it so that equal force shows as an equal value ("g" toggles it).

Start options:
  python Visualizer/hand_heatmap.py          gains applied (if hand_layout.json has them)
  python Visualizer/hand_heatmap.py --raw    sensor values as they are (no gains)
  --vmax N                                   colour scale maximum at start (default 100)

Keys (on the plot window):
  g      toggle force-scale gains (from hand_gain_calibrate.py)
  a      toggle area normalisation (counts / cm²  <->  counts)
  b      re-capture baseline (keep hands off)
  + / -  raise / lower the colour scale maximum
  l      toggle channel labels
"""

import argparse
import json
import os
import sys

import matplotlib.pyplot as plt
import matplotlib.animation as animation
from matplotlib.collections import PatchCollection
from matplotlib.patches import Polygon
import matplotlib.patheffects as pe
import serial

from icepizeroo import (BAUD, BASELINE_SAMPLES, NUM_SENSORS,
                        find_active_port, find_packet, parse_packet)

LAYOUT_FILE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "hand_layout.json")
VMAX_START = {True: 50, False: 100}   # full colour: counts/cm² (normalised) or counts
VMAX_STEPS = [5, 10, 25, 50, 100, 200, 300, 500, 1000, 2000, 5000]
NORMALISE_START = False
USE_GAIN_START = True    # only if hand_layout.json has gains
TOUCH_THRESHOLD = 15    # same as icepizeroo.py
SMOOTHING = 0.3         # EMA weight of each new frame (1.0 = no smoothing)
CMAP = "inferno_r"

# free "l" from matplotlib's default shortcut (toggle log y-scale)
plt.rcParams["keymap.yscale"] = []
plt.rcParams["keymap.grid"] = []      # free "g" (toggle grid)


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description="Hand taxel heatmap")
    ap.add_argument("--raw", action="store_true", help="show sensor values without gains")
    ap.add_argument("--vmax", type=float, help="colour scale maximum at start")
    args = ap.parse_args()

    with open(LAYOUT_FILE) as f:
        layout = json.load(f)
    taxels = layout["taxels"]

    PORT = find_active_port()
    if PORT is None:
        print("ERROR: No COM port is sending the expected data (header 0xAB, footer 0xFF).")
        sys.exit(1)
    print(f"Using {PORT} @ {BAUD}")
    try:
        ser = serial.Serial(PORT, BAUD, timeout=0.05)
        ser.reset_input_buffer()
    except serial.SerialException as e:
        print(f"ERROR: {e}")
        sys.exit(1)

    buf = bytearray()
    baseline = [0] * NUM_SENSORS
    baseline_ready = False
    baseline_acc = [0] * NUM_SENSORS
    baseline_cnt = 0
    shown = [0.0] * NUM_SENSORS     # smoothed, baseline-corrected values
    normalise = NORMALISE_START
    has_gain = any(t.get("gain") is not None for t in taxels)
    use_gain = USE_GAIN_START and has_gain and not args.raw
    vmax = dict(VMAX_START)         # separate scale for each mode
    if args.vmax:
        vmax[normalise] = args.vmax

    def capture_baseline():
        global baseline_ready, baseline_acc, baseline_cnt
        baseline_ready = False
        baseline_acc = [0] * NUM_SENSORS
        baseline_cnt = 0
        print("Capturing new baseline - keep hands off the sensors...")

    # ── plot setup ──
    fig, ax = plt.subplots(figsize=(11, 8))
    fig.canvas.manager.set_window_title("Hand Heatmap")
    ax.set_aspect("equal")
    ax.axis("off")

    for pts in layout["outline"]:
        xs, ys = zip(*pts)
        ax.plot(xs, ys, color="0.3", linewidth=1.0)

    # one patch per polygon; taxels made of two shapes get two patches
    # taxels without a channel (null in hand_layout.json) are drawn grey
    def area_cm2(t):
        a = 0.0
        for p in t["polygons"]:
            a += abs(sum(p[i][0] * p[i - 1][1] - p[i - 1][0] * p[i][1] for i in range(len(p)))) / 2
        return a / 100.0

    patches, patch_channel, patch_area, patch_gain = [], [], [], []
    for t in taxels:
        for pts in t["polygons"]:
            if t["channel"] is None:
                ax.add_patch(Polygon(pts, closed=True, facecolor="0.85", edgecolor="0.2",
                                     linewidth=0.6, hatch="//"))
                continue
            patches.append(Polygon(pts, closed=True))
            patch_channel.append(t["channel"])
            patch_area.append(area_cm2(t))
            patch_gain.append(t.get("gain") or 1.0)
    coll = PatchCollection(patches, cmap=CMAP, edgecolor="0.2", linewidth=0.6)
    coll.set_array([0.0] * len(patches))
    ax.add_collection(coll)
    cbar = fig.colorbar(coll, ax=ax, fraction=0.03, pad=0.02)

    def apply_mode():
        coll.set_clim(0, vmax[normalise])
        g = " × gain" if use_gain else ""
        if normalise:
            ax.set_title(f"Icepi Zero – hand taxels (count − baseline){g} / area")
            cbar.set_label(f"(count − baseline){g} / cm²")
        else:
            ax.set_title(f"Icepi Zero – hand taxels (count − baseline){g}")
            cbar.set_label(f"count − baseline{g}")
        fig.canvas.draw_idle()

    apply_mode()

    labels = []
    for t in taxels:
        pts = max(t["polygons"], key=len)
        cx = sum(p[0] for p in pts) / len(pts)
        cy = sum(p[1] for p in pts) / len(pts)
        label = f"S{t['channel']}" if t["channel"] is not None else "-"
        labels.append(ax.text(cx, cy, label, ha="center", va="center",
                              fontsize=8, color="tab:blue", weight="bold",
                              path_effects=[pe.withStroke(linewidth=2.5, foreground="white")]))

    mapped = {t["channel"] for t in taxels if t["channel"] is not None}
    unmapped = [c for c in range(NUM_SENSORS) if c not in mapped]
    status_text = ax.text(0.01, 0.99, "", transform=ax.transAxes, va="top",
                          fontsize=9, family="monospace",
                          bbox=dict(boxstyle="round", facecolor="wheat", alpha=0.8))

    capture_baseline()

    def update(_frame):
        global buf, baseline_ready, baseline_acc, baseline_cnt, baseline

        data = ser.read(ser.in_waiting or 1)
        if data:
            buf.extend(data)

        acc = [0] * NUM_SENSORS
        n = 0
        while True:
            pkt, buf = find_packet(buf)
            if pkt is None:
                break
            raw_vals = [v for _, v in parse_packet(pkt)]
            if not baseline_ready:
                for i, v in enumerate(raw_vals):
                    baseline_acc[i] += v
                baseline_cnt += 1
                if baseline_cnt >= BASELINE_SAMPLES:
                    for i in range(NUM_SENSORS):
                        baseline[i] = baseline_acc[i] // baseline_cnt
                    baseline_ready = True
                    print("Baseline captured:", baseline)
                continue
            for i, v in enumerate(raw_vals):
                acc[i] += max(0, v - baseline[i])
            n += 1

        if not baseline_ready:
            status_text.set_text(f"Capturing baseline… {baseline_cnt}/{BASELINE_SAMPLES}")
            return [coll, status_text]
        if n:
            for i in range(NUM_SENSORS):
                shown[i] += SMOOTHING * (acc[i] / n - shown[i])

        vals = [shown[c] * (g if use_gain else 1.0) / (a if normalise else 1.0)
                for c, a, g in zip(patch_channel, patch_area, patch_gain)]
        coll.set_array(vals)
        k = max(range(len(vals)), key=lambda j: vals[j])
        unit = "/cm²" if normalise else ""
        lines = [f"max: S{patch_channel[k]} = {vals[k]:6.0f}{unit}   scale 0–{vmax[normalise]}{unit}"
                 "  (+/- scale, g = gain, a = area norm, b = baseline)"]
        if unmapped:
            lines.append("not on hand: " + " ".join(
                f"S{c}={shown[c]:.0f}" + ("*" if shown[c] > TOUCH_THRESHOLD else "") for c in unmapped))
        status_text.set_text("\n".join(lines))
        return [coll, status_text]

    def on_key(event):
        global normalise, use_gain
        if event.key == "b":
            capture_baseline()
        elif event.key == "g" and has_gain:
            use_gain = not use_gain
            apply_mode()
        elif event.key == "a":
            normalise = not normalise
            apply_mode()
        elif event.key in ("+", "=", "-"):
            i = min(range(len(VMAX_STEPS)), key=lambda k: abs(VMAX_STEPS[k] - vmax[normalise]))
            i = min(i + 1, len(VMAX_STEPS) - 1) if event.key != "-" else max(i - 1, 0)
            vmax[normalise] = VMAX_STEPS[i]
            coll.set_clim(0, vmax[normalise])
        elif event.key == "l":
            for t in labels:
                t.set_visible(not t.get_visible())

    fig.canvas.mpl_connect("key_press_event", on_key)
    ani = animation.FuncAnimation(fig, update, interval=30,
                                  blit=False, cache_frame_data=False)

    print("Hand heatmap running - keep hands off for the first second (baseline capture)")
    try:
        plt.show()
    except KeyboardInterrupt:
        pass
    finally:
        ser.close()
        print("Closed.")
